// New order page (/orders/new): pick a customer, add product lines, place the order.
// The backend checks stock, deducts it and emails the customer.
import { useFieldArray, useWatch } from "react-hook-form";
import { Link, useNavigate } from "react-router-dom";
import useApi from "../hooks/useApi";
import useZodForm from "../hooks/useZodForm";
import { ordersApi, productsApi, usersApi } from "../api/resources";
import { orderSchema } from "../validation/orderSchema";
import { formatCurrency } from "../utils/format";
import Alert from "../components/ui/Alert";
import AsyncState from "../components/ui/AsyncState";
import FormField from "../components/ui/FormField";
import PageHeader from "../components/ui/PageHeader";
import SubmitButton from "../components/ui/SubmitButton";

// ---------- Data loading (customers + products in parallel) ----------
const loadOptions = async () => {
  const [customers, products] = await Promise.all([usersApi.list(), productsApi.list()]);
  return { customers, products };
};

const EMPTY_LINE = { productId: "", quantity: 1 };

function NewOrder() {
  const query = useApi(loadOptions);

  return (
    <>
      <Link to="/orders" className="back-link">← Back to orders</Link>
      <PageHeader title="New order" subtitle="Stock is checked and deducted when the order is placed." />

      <AsyncState {...query}>{query.data && <OrderForm {...query.data} />}</AsyncState>
    </>
  );
}

// ---------- The form (rendered once customers + products are loaded) ----------
function OrderForm({ customers, products }) {
  const navigate = useNavigate();

  // ---------- Form setup ----------
  const {
    register,
    control,
    submit,
    formState: { errors, isSubmitting },
  } = useZodForm(orderSchema, { userId: "", items: [EMPTY_LINE] });

  // Dynamic list of product lines
  const { fields, append, remove } = useFieldArray({ control, name: "items" });

  // Live values, used for line subtotals and the order total
  const lines = useWatch({ control, name: "items" });

  // ---------- Derived values ----------
  const productById = new Map(products.map((p) => [p.id, p]));
  const lineTotal = (line) => (productById.get(line?.productId)?.price ?? 0) * (Number(line?.quantity) || 0);
  const orderTotal = lines.reduce((sum, line) => sum + lineTotal(line), 0);
  const chosenIds = lines.map((line) => line.productId);

  // ---------- Submit ----------
  async function placeOrder(values) {
    const order = await ordersApi.create(values);
    navigate(`/orders/${order.id}`);
  }

  // ---------- Nothing to order with yet ----------
  if (!customers.length || !products.length) {
    return (
      <Alert type="info">
        You need at least one customer and one product first.{" "}
        <Link to="/customers">Add a customer</Link> · <Link to="/products">Add a product</Link>
      </Alert>
    );
  }

  // ---------- Markup ----------
  return (
    <form className="card form" onSubmit={submit(placeOrder)} noValidate>
      <Alert>{errors.root?.message}</Alert>

      <FormField label="Customer" error={errors.userId}>
        <select {...register("userId")}>
          <option value="">Select a customer…</option>
          {customers.map((c) => (
            <option key={c.id} value={c.id}>
              {c.username} ({c.email})
            </option>
          ))}
        </select>
      </FormField>

      <h2>Products</h2>
      {fields.map((field, index) => (
        // field.id is a stable key generated by useFieldArray
        <div key={field.id} className="order-line">
          <FormField error={errors.items?.[index]?.productId}>
            <select {...register(`items.${index}.productId`)} aria-label="Product">
              <option value="">Select a product…</option>
              {products.map((p) => (
                <option
                  key={p.id}
                  value={p.id}
                  // can't pick an out-of-stock product or one already used on another line
                  disabled={p.stockQuantity === 0 || (chosenIds.includes(p.id) && p.id !== lines[index]?.productId)}
                >
                  {p.name} — {formatCurrency(p.price)} ({p.stockQuantity} left)
                </option>
              ))}
            </select>
          </FormField>

          <FormField error={errors.items?.[index]?.quantity}>
            <input
              type="number"
              min="1"
              max={productById.get(lines[index]?.productId)?.stockQuantity}
              {...register(`items.${index}.quantity`)}
              aria-label="Quantity"
            />
          </FormField>

          <span className="order-line-total">{formatCurrency(lineTotal(lines[index]))}</span>

          <button
            type="button"
            className="btn btn-ghost btn-sm"
            onClick={() => remove(index)}
            disabled={fields.length === 1}
            aria-label="Remove line"
          >
            ✕
          </button>
        </div>
      ))}

      {/* array-level errors (e.g. same product twice) */}
      <Alert>{errors.items?.root?.message ?? errors.items?.message}</Alert>

      <button
        type="button"
        className="btn btn-ghost"
        onClick={() => append(EMPTY_LINE)}
        disabled={fields.length >= products.length}
      >
        + Add another product
      </button>

      <div className="order-summary">
        <span>Total</span>
        <strong>{formatCurrency(orderTotal)}</strong>
      </div>

      <div className="form-actions">
        <Link to="/orders" className="btn btn-ghost">Cancel</Link>
        <SubmitButton loading={isSubmitting}>Place order</SubmitButton>
      </div>
    </form>
  );
}

export default NewOrder;
